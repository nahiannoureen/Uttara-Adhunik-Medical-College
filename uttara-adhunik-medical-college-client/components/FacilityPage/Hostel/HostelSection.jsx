import React from "react";

const GREEN = "#018837";

async function getHostelService() {
  try {
    const response = await fetch(
      `${process.env.NEXT_PUBLIC_ADMIN_API}/api/facility/hostel-service/hostel`,
      {
        // Change to `cache: "no-store"` if you need the API
        // to be requested on every page request.
        cache: "no-store",
      },
    );

    if (!response.ok) {
      throw new Error(`Failed to fetch hostel service: ${response.status}`);
    }

    const data = await response.json();

    return data?.[0] ?? null;
  } catch (error) {
    console.error("Hostel service API error:", error);
    return null;
  }
}

export default async function HostelSection() {
  const hostel = await getHostelService();

  // API title fallback
  const title = hostel?.title || "Hostel Services";

  // Split title so the first word can use the green color.
  // Example: "Hostel Services" -> "Hostel" + "Services"
  const titleParts = title.trim().split(/\s+/);
  const firstWord = titleParts[0] || "Hostel";
  const remainingWords = titleParts.slice(1).join(" ");

  return (
    <section className="w-full bg-[#E6F4EB] px-4 py-12 sm:px-6 sm:py-14 md:px-10 md:py-16 lg:px-16 lg:py-20 xl:px-20">
      <div className="mx-auto flex w-full max-w-[1440px] flex-col gap-8 sm:gap-10 lg:gap-12">
        {/* Top Content */}
        <div className="flex w-full flex-col items-center justify-between gap-8 lg:flex-row lg:gap-12">
          {/* Left Side */}
          <div className="flex w-full flex-1 items-center justify-center lg:justify-start">
            <div className="flex w-full items-center gap-4 sm:gap-5 md:gap-6 lg:max-w-[550px]">
              {/* Hostel Icon */}
              <div className="flex h-20 w-20 shrink-0 items-center justify-center sm:h-24 sm:w-24 md:h-28 md:w-28 lg:h-[120px] lg:w-[120px]">
                <img
                  src="/host.png"
                  alt={title}
                  className="h-full w-full object-contain"
                />
              </div>

              {/* Dynamic Title */}
              <div className="flex min-w-0 flex-1 flex-col justify-center">
                <h1
                  className="m-0 break-words font-['Bitter'] text-3xl font-bold leading-tight tracking-[0.01em] sm:text-4xl md:text-5xl lg:text-[50px] lg:leading-[1.15]"
                  style={{ color: GREEN }}
                >
                  {firstWord}
                </h1>

                {remainingWords && (
                  <h1 className="m-0 break-words font-['Bitter'] text-3xl font-bold leading-tight tracking-[0.01em] text-black sm:text-4xl md:text-5xl lg:text-[50px] lg:leading-[1.15]">
                    {remainingWords}
                  </h1>
                )}
              </div>
            </div>
          </div>

          {/* Right Side */}
          <div className="flex w-full flex-1 items-center justify-center lg:justify-end">
            <div className="w-full max-w-[683px]">
              <p className="m-0 font-['Bitter'] text-base font-normal leading-7 tracking-[0.01em] text-[#444444] sm:text-lg sm:leading-7 md:text-xl md:leading-[30px]">
                <strong className="font-bold">UAMC</strong> provides comfortable
                and convenient hostel facilities designed to offer a safe and
                welcoming environment for students, patients, and their
                attendants. The hostel services support a peaceful stay with
                essential facilities, ensuring comfort, convenience, and a
                supportive environment throughout their time at the medical
                college.
              </p>
            </div>
          </div>
        </div>
      </div>
    </section>
  );
}
